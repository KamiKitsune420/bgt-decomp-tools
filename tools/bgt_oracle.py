class OracleError(Exception):
    """The check could not be run, as opposed to having failed.

    Kept distinct on purpose: **a check that cannot run is worse than no
    check**, because it is counted. The NVGT round-trip fixture skipped
    silently without a compiler and then died in `subprocess` with one, so
    774 lines of decompiler change landed with it inert.
    """


def fixture_source() -> str:
    return SOURCE.replace("REPORT_NAME", REPORT)


def _read_report(folder: str) -> Dict[str, str]:
    path = os.path.join(folder, REPORT)
    if not os.path.exists(path):
        raise OracleError("%s wrote no %s -- it was built but did not run to the "
                          "end" % (os.path.basename(folder), REPORT))
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        text = fh.read()
    out: Dict[str, str] = {}
    for entry in text.split("|"):
        if "=" in entry:
            key, _, value = entry.partition("=")
            out[key.strip()] = value.strip()
    if not out:
        raise OracleError("%s is empty" % path)
    return out


def _build(script: str, compiler: Optional[str], timeout: float) -> str:
    """Compile `script` to an executable and return its path.

    The artifact is what `bgt_compile` checks for: BGT writes it only after
    its report window is answered and writes none at all for a script section
    it calls empty, so a clean report is not evidence that a file exists.
    """
    report = bgt_compile.check(script, compiler=compiler, timeout=timeout,
                               build="release")
    if not report.ok:
        raise OracleError("%s: %s" % (os.path.basename(script), report.summary()))
    return bgt_compile.built_path(script)


def _run(exe: str, timeout: float) -> None:
    folder = os.path.dirname(exe)
    stale = os.path.join(folder, REPORT)
    if os.path.exists(stale):
        # A previous run's report read as this one's is the one way this check
        # can pass without having run.
        os.unlink(stale)
    try:
        subprocess.run([exe], cwd=folder, timeout=timeout,
                       stdin=subprocess.DEVNULL, capture_output=True)
    except subprocess.TimeoutExpired:
        raise OracleError("%s did not exit within %ds -- a runtime error dialog "
                          "waits for someone" % (os.path.basename(exe), int(timeout)))
    except OSError as exc:
        raise OracleError("%s would not start (%s)" % (os.path.basename(exe), exc))


def check(out_dir: str, compiler: Optional[str] = None, timeout: float = 600.0,
          stock_includes: bool = True,
          progress=lambda message: None) -> Dict[str, object]:
    """Round-trip the fixture and compare what the two builds compute."""
    os.makedirs(out_dir, exist_ok=True)
    original = os.path.join(out_dir, "original")
    os.makedirs(original, exist_ok=True)
    script = os.path.join(original, "oracle.bgt")
    with open(script, "w", encoding="utf-8") as fh:
        fh.write(fixture_source())

    progress("compiling the fixture")
    exe = _build(script, compiler, timeout)
    progress("running it for the known answer")
    _run(exe, timeout)
    expected = _read_report(original)

    progress("recovering it")
    recovered_dir = os.path.join(out_dir, "recovered")
    project = bgt_project.recover(exe, recovered_dir, make_zip=False,
                                  with_data=False, stock_includes=stock_includes,
                                  progress=lambda message: None)
    progress("building the recovery")
    entry = os.path.join(recovered_dir, project.entry)
    rebuilt = _build(entry, compiler, timeout)
    identified = engine.identify(rebuilt)
    progress("running the recovery")
    _run(rebuilt, timeout)
    actual = _read_report(recovered_dir)

    shapes: List[Tuple[str, str, str, bool]] = []
    for key, want in expected.items():
        got = actual.get(key, "<missing>")
        shapes.append((key, want, got, want == got))
    extra = [k for k in actual if k not in expected]
    return {
        "shapes": shapes,
        "agreed": sum(1 for _, _, _, ok in shapes if ok),
        "total": len(shapes),
        "extra": extra,
        "engine": identified.summary() if identified is not None else "",
        "stats": _stats(recovered_dir),
    }


def _stats(recovered_dir: str) -> Dict[str, object]:
    """The recovery's own numbers, read from what it wrote.

    From `recovery.json` rather than from the `Project` in hand, so the
    oracle reports the same figures anyone re-running `bgt recover` would
    read, and cannot quote a field that only exists in memory.
    """
    path = os.path.join(recovered_dir, "recovery.json")
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh).get("stats", {})
    except (OSError, ValueError):
        return {}


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        prog="bgt oracle",
        description=__doc__.split("\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--out", help="where to work (default: a temp folder)")
    ap.add_argument("--compiler", help="path to bgt.exe")
    ap.add_argument("--timeout", type=float, default=600.0)
    ap.add_argument("--no-stock-includes", action="store_true",
                    help="keep every file decompiled, substituting none")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)

    out = args.out
    if not out:
        import tempfile
        out = os.path.join(tempfile.gettempdir(), "bgt_oracle")
    try:
        result = check(out, compiler=args.compiler, timeout=args.timeout,
                       stock_includes=not args.no_stock_includes,
                       progress=lambda m: None if args.json else print("  %s" % m))
    except OracleError as exc:
        # Not a failure of the recovery: the check did not run. Said plainly,
        # because an outcome with no explanation reads like a result.
        print("could not run the oracle: %s" % exc)
        return 2

    if args.json:
        print(json.dumps(result, indent=2, default=str))
    else:
        for key, want, got, ok in result["shapes"]:
            print("  %-28s %-10s %-10s %s" % (key, want, got, "ok" if ok else "WRONG"))
        print("%d/%d shapes compute the same value" % (result["agreed"], result["total"]))
        if result["engine"]:
            print("the rebuilt executable is %s" % result["engine"])
    return 0 if result["agreed"] == result["total"] else 1


if __name__ == "__main__":
    sys.exit(main())
