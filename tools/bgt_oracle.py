"""`bgt oracle`: a source whose answer is known, round-tripped through the engine.

Every other check here asks whether the recovery is *valid*. This one asks
whether it is the **same program**, and it can, because BGT compiles: hand the
engine a source written here, and the answer to "what should this do?" is not
inferred from the bytecode -- it was decided before the bytecode existed.

    oracle.bgt  --BGT-->  oracle.exe  --run-->  report A
                              |
                         bgt recover
                              v
                     recovered project  --BGT-->  exe  --run-->  report B

A mismatch between A and B is a decompiler defect, named by shape, with no
game file involved. That matters because the failure mode this toolkit keeps
hitting is a recovery that compiles cleanly, runs, opens its window and then
computes something else -- which no diagnostic count, window title or
`libcheck` score can see. Three such bugs in Super Egg Hunt were found by
someone pressing an arrow key; `counter` below finds that class mechanically.

**The fixture is generated rather than shipped as data**, so this folder keeps
holding only the document and the Python tools, and the known answer stays
next to the question it answers.

What each shape is for:

* The `declared_*` family asks whether a value the source **named** survives as
  a variable. `bump()` returns a different number every call, so folding one
  into several reads does not merely read worse -- it runs the call again and
  computes something the source never did. `counter` is the whole module's
  duplication detector: nine calls, and any duplicated or dropped one moves it.
* `temp_in_condition`, `temp_in_short_circuit` and `ternary_result` are the
  other half, and they are why "fold less" is not the fix. A loop condition
  promoted to a statement before a jump stops being a loop condition, and
  Super Egg Hunt went from 0 residual gotos to 182 that way -- which is 187
  compiler errors, since AngelScript has no `goto`.
* `dead_local_other`, with `counter`, is the dropped call: a call whose result
  is stored in a local the original never reads. Dropping an expression
  nothing reads is behaviour-preserving only while the expression is PURE,
  and a call is not -- Manamon 1's `sound_pool_item::load_sound` lost both
  its `load` and its `stream` that way, so a recovered sound pool loads
  nothing. The per-arm shape is the one that rules out an end-of-body sweep:
  by `RET` the slot holds whichever arm ran last.
* `snapshot_across_mutation` is Paladin's `calculate_experience`: snapshots
  taken before a mutating call and reported after it. Folded, the comparison
  reads `if (level == level)`, so a level-up is silent and reports `+0`.
* `stale_read_across_removal` is Paladin's `add_event`, which killed every
  save that had ever replaced an event: the index is reassigned and the
  element removed between the read and its use.
* `loop_mid_continue` is `register_software`, where the `continue` sits in the
  middle of the body. Read as the loop's tail it cut the body in half and
  registration could never succeed.
"""
